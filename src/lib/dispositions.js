// ============================================================
// REPORTING METADATA
// ============================================================

export function getDispositionReportingMeta({
  status,
  subStatus,
}) {
  let rule = null;

  if (subStatus) {
    rule =
      DISPOSITION_RULES.find(
        (item) =>
          item.status ===
            status &&
          item.subStatus ===
            subStatus
      );
  }

  if (!rule) {
    rule =
      DISPOSITION_RULES.find(
        (item) =>
          item.status ===
            status &&
          item.defaultForStatus
      );
  }

  if (!rule) {
    return {
      reportingCategory:
        "Unclassified",

      productive:
        false,

      countsInUtilization:
        false,

      requiresApproval:
        false,

      requestOnly:
        false,

      automaticOnly:
        false,
    };
  }

  return {
    reportingCategory:
      rule.reportingCategory,

    productive:
      rule.productive,

    countsInUtilization:
      rule.countsInUtilization,

    requiresApproval:
      rule.requiresApproval,

    requestOnly:
      rule.requestOnly,

    automaticOnly:
      rule.automaticOnly,
  };
}


