// ============================================================
// NORMALIZATION
// ============================================================

export function normalizeLob(lob) {
  const value =
    String(lob || "").trim();

  const lower =
    value.toLowerCase();

  if (
    lower === "lc" ||
    lower === "lending creative" ||
    lower === "lendingcreative"
  ) {
    return LENDING_CREATIVE;
  }

  if (
    lower === "goday" ||
    lower === "go day"
  ) {
    return GODAY;
  }

  return value;
}


export function normalizeDepartment(
  department
) {
  const value =
    String(department || "").trim();

  const lower =
    value.toLowerCase();

  const aliases = {
    "customer service": "CS",

    "customer service / loan officer":
      "CS/LO",

    "cs / lo":
      "CS/LO",

    "cs/lo":
      "CS/LO",

    collections:
      "Collector",

    collector:
      "Collector",

    "loan officer":
      "LO",

    lo:
      "LO",

    returning:
      "RET",

    "returning customer":
      "RET",

    ret:
      "RET",

    documents:
      "Documents",

    emails:
      "Emails",

    cls:
      "CLS",
  };

  return aliases[lower] || value;
}


// ============================================================
// LOB / DEPARTMENT MATCHING
// ============================================================

function matchesLob(
  rule,
  lob
) {
  if (
    rule.lobs.includes(ALL)
  ) {
    return true;
  }

  const normalizedLob =
    normalizeLob(lob);

  return rule.lobs
    .map(normalizeLob)
    .includes(
      normalizedLob
    );
}


function matchesDepartment(
  rule,
  department
) {
  if (
    rule.departments.includes(
      ALL
    )
  ) {
    return true;
  }

  const normalizedDepartment =
    normalizeDepartment(
      department
    );

  return rule.departments
    .map(
      normalizeDepartment
    )
    .includes(
      normalizedDepartment
    );
}


// ============================================================
// PRIMARY STATUS VISIBILITY
// ============================================================

export function getAvailablePrimaryStatuses(
  user
) {
  const leadership =
    isDispositionLeadership(
      user
    );

  return PRIMARY_STATUS_CONFIG
    .filter((item) => {
      if (
        !item.employeeSelectable
      ) {
        return false;
      }

      if (
        item.leadershipOnly &&
        !leadership
      ) {
        return false;
      }

      return true;
    })
    .map(
      (item) =>
        item.status
    );
}


// ============================================================
// NORMAL SECONDARY DROPDOWN
//
// IMPORTANT:
//
// requestOnly items are excluded.
//
// Therefore:
//
// Break -> Extra Time Off
//
// will NOT appear inside the normal Break workflow.
// ============================================================

export function getAvailableSubStatuses({
  status,
  lob,
  department,
  role,
  accessLevel,
  user,
}) {
  const leadership =
    isDispositionLeadership(
      user ||
      accessLevel ||
      role
    );

  let rules =
    DISPOSITION_RULES.filter(
      (rule) =>
        rule.status === status &&
        rule.showInSecondaryDropdown &&
        !rule.automaticOnly &&
        !rule.requestOnly
    );

  // Leadership sees all normal manual options.
  if (!leadership) {
    rules =
      rules.filter(
        (rule) =>
          matchesLob(
            rule,
            lob
          ) &&
          matchesDepartment(
            rule,
            department
          ) &&
          !rule.leadershipOnly
      );
  }

  return [
    ...new Set(
      rules.map(
        (rule) =>
          rule.subStatus
      )
    ),
  ];
}


// ============================================================
// REQUESTABLE DISPOSITIONS
//
// Used later by App.jsx for things such as:
//
// [ Request Extra Time Off ]
//
// This is deliberately separate from normal status changes.
// ============================================================

export function getRequestableDispositions({
  lob,
  department,
  role,
  accessLevel,
  user,
}) {
  const leadership =
    isDispositionLeadership(
      user ||
      accessLevel ||
      role
    );

  let rules =
    DISPOSITION_RULES.filter(
      (rule) =>
        rule.requestOnly &&
        !rule.automaticOnly
    );

  if (!leadership) {
    rules =
      rules.filter(
        (rule) =>
          matchesLob(
            rule,
            lob
          ) &&
          matchesDepartment(
            rule,
            department
          ) &&
          !rule.leadershipOnly
      );
  }

  return rules.map(
    (rule) => ({
      status:
        rule.status,

      subStatus:
        rule.subStatus,

      requiresApproval:
        rule.requiresApproval,

      reportingCategory:
        rule.reportingCategory,

      captureMethod:
        rule.captureMethod,
    })
  );
}


