// ============================================================
// VALIDATION
// ============================================================

export function validateDisposition({
  status,
  subStatus,
}) {
  if (!status) {
    return {
      valid: false,
      message:
        "Select a status.",
    };
  }

  if (
    isSecondaryRequired(
      status
    ) &&
    !subStatus
  ) {
    return {
      valid: false,
      message:
        "Please select a reason.",
    };
  }

  return {
    valid: true,
    message: "",
  };
}