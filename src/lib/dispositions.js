// ============================================================
// LEADERSHIP ROLES
//
// TL / Manager / Leadership:
// - See all manual disposition options.
// - Can approve Extra Time Off requests later.
// ============================================================

export const LEADERSHIP_ROLES = [
  "Team Leader",
  "Sr. Team Leader",
  "Manager",
  "Collector Supervisor",
  "Supervisor",
  "Q&T Manager",
  "Quality & Training Manager",
  "Business Director",
  "Executive",
  "COO",
  "Admin",
];

export function isDispositionLeadership(
  userOrRole
) {
  const rawRole =
    typeof userOrRole === "string"
      ? userOrRole
      : userOrRole?.access_level ||
        userOrRole?.role ||
        userOrRole?.title ||
        "";

  const role = String(rawRole)
    .trim()
    .toLowerCase();

  if (!role) {
    return false;
  }

  const exactMatch =
    LEADERSHIP_ROLES.some(
      (item) =>
        item.toLowerCase() === role
    );

  if (exactMatch) {
    return true;
  }

  return (
  role.includes("team leader") ||
  role.includes("manager") ||
  role.includes("supervisor") ||
  role.includes("executive") ||
  role.includes("director") ||
  role === "coo" ||
  role === "admin"
);
}


