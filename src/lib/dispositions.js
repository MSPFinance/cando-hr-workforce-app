export function getDefaultSubStatus(
  status
) {
  const defaultRule =
    DISPOSITION_RULES.find(
      (rule) =>
        rule.status ===
          status &&
        rule.defaultForStatus
    );

  return (
    defaultRule?.subStatus ||
    null
  );
}


